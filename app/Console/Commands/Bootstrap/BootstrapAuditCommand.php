<?php

namespace App\Console\Commands\Bootstrap;

use App\Support\Bootstrap\Census;
use Illuminate\Console\Command;

/**
 * Bootstrap Phase 0 (read-only): writes docs/BOOTSTRAP-AUDIT.md from a static census of the code. Re-run it after any wave of features; the audit is the plan, so a stale one is a lie.
 */
class BootstrapAuditCommand extends Command
{
    protected $signature = 'naara:bootstrap:audit {--out=docs/BOOTSTRAP-AUDIT.md}';

    protected $description = 'Census of settings, notifications, scheduled jobs, features and credential slots (read-only)';

    public function handle(): int
    {
        $settings = Census::settings();
        $dynamic = Census::dynamicSettingReads();
        $notifs = Census::notifications();
        $sched = Census::scheduler();
        $features = Census::features();
        $mail = Census::mailTemplates();
        $env = Census::serviceEnv();

        $groups = [];
        foreach ($settings as $s) {
            $groups[$s['group']][] = $s;
        }
        ksort($groups);

        $seeded = count(array_filter($settings, fn ($s) => $s['seeded']));
        $literal = count(array_filter($settings, fn ($s) => $s['has_literal']));
        $unresolved = count($settings) - $literal;

        $md = [];
        $md[] = '# BOOTSTRAP-AUDIT (Phase 0, generated)';
        $md[] = '';
        $md[] = '> Generated by `php artisan naara:bootstrap:audit` from a static scan of this checkout. Numbers below come from the code, not from the blueprint. Regenerate after every feature wave.';
        $md[] = '> Scope: the branch this was run on. Business Suite and NaaraBrain live on their own branches and appear here only once merged.';
        $md[] = '';
        $md[] = '## Summary';
        $md[] = '';
        $md[] = '| Census | Count |';
        $md[] = '|---|---|';
        $md[] = '| Literal `Setting` keys read in code | '.count($settings).' ('.count($groups).' groups) |';
        $md[] = '| ...already seeded by a seeder | '.$seeded.' |';
        $md[] = '| ...with a plain literal code default (can be seeded as-is) | '.$literal.' |';
        $md[] = '| ...default is a constant/expression (needs a human) or has none | '.$unresolved.' |';
        $md[] = '| Dynamic `Setting` reads that cannot be listed literally | '.count($dynamic).' |';
        $md[] = '| Notification classes | '.count($notifs).' |';
        $md[] = '| Email Studio templates | '.count($mail).' |';
        $md[] = '| Scheduled statements in routes/console.php | '.count($sched).' (without overlap guard: '.count(array_filter($sched, fn ($s) => ! $s['overlap_guard'])).') |';
        $md[] = '| Feature flags (`FeatureFlags::FEATURES`) | '.count($features).' |';
        $md[] = '| Provider blocks with env credentials in config/services.php | '.count($env).' |';
        $md[] = '';
        $md[] = '**Finding (corrects the blueprint):** every scheduled command already writes a heartbeat row, because `AppServiceProvider` listens to the console Starting/Finished/Failed/Skipped events (`app/Support/JobHeartbeats.php`). The job manifest therefore needs no per-command wiring; it needs to be *shown* (Setup Health).';
        $md[] = '';
        $md[] = '## 1. Setting census by group';
        $md[] = '';
        foreach ($groups as $g => $rows) {
            $md[] = '### `'.$g.'` ('.count($rows).') - risk: '.$rows[0]['risk'];
            $md[] = '';
            $md[] = '| Key | Code default | Seeded | Read in |';
            $md[] = '|---|---|---|---|';
            foreach ($rows as $s) {
                $def = $s['has_literal'] ? '`'.json_encode($s['literal']).'`' : ($s['defaults'] === [] || $s['defaults'] === [''] ? '(none)' : '(expression)');
                $md[] = '| `'.$s['key'].'` | '.$def.' | '.($s['seeded'] ? 'yes' : 'no').' | `'.str_replace(base_path().'/', '', $s['files'][0] ?? '').'` |';
            }
            $md[] = '';
        }
        $md[] = '### Dynamic reads (not in the list above)';
        $md[] = '';
        foreach ($dynamic as $d) {
            $md[] = '- `'.$d.'`';
        }
        $md[] = '';
        $md[] = '## 2. Notification census';
        $md[] = '';
        $md[] = '| Class | Channels | Master-only |';
        $md[] = '|---|---|---|';
        foreach ($notifs as $n => $row) {
            $md[] = '| `'.$n.'` | '.($row['channels'] ? implode(', ', $row['channels']) : '(dynamic)').' | '.($row['master_only'] ? 'yes' : 'no').' |';
        }
        $md[] = '';
        $md[] = 'Email Studio templates today: '.implode(', ', array_map(fn ($k) => '`'.$k.'`', array_keys($mail))).'. Template coverage is below notification coverage; the notification catalog (`config/notification_catalog.php`) closes the bookkeeping gap and a test keeps it closed.';
        $md[] = '';
        $md[] = '## 3. Scheduler census';
        $md[] = '';
        $md[] = '| Command | Frequency | `withoutOverlapping` |';
        $md[] = '|---|---|---|';
        foreach ($sched as $s) {
            $md[] = '| `'.$s['command'].'` | '.$s['frequency'].' | '.($s['overlap_guard'] ? 'yes' : '**no**').' |';
        }
        $md[] = '';
        $md[] = '## 4. Feature flags';
        $md[] = '';
        $md[] = '| Feature | Group | Default | Needs |';
        $md[] = '|---|---|---|---|';
        foreach ($features as $k => $f) {
            $md[] = '| `'.$k.'` ('.$f['name'].') | '.$f['group'].' | '.($f['default'] ? 'on' : 'off').' | '.($f['requires'] ? '`'.implode('`, `', $f['requires']).'`' : '(nothing)').' |';
        }
        $md[] = '';
        $md[] = '## 5. Credential slots (from config/services.php)';
        $md[] = '';
        $md[] = '| Provider block | Env variables |';
        $md[] = '|---|---|';
        foreach ($env as $p => $vars) {
            $md[] = '| `'.$p.'` | `'.implode('`, `', array_unique($vars)).'` |';
        }
        $md[] = '';
        $md[] = '## 6. Open items';
        $md[] = '';
        $md[] = '- Keys whose default is an expression or constant are **not** auto-seeded; `config/bootstrap/settings.php` lists only keys with a plain literal default, so seeding can never change behaviour.';
        $md[] = '- Admin-screen empty-state quality, public-claim review and the docs-vs-code mismatch report need a human (or browser) pass and are tracked in `PROGRESS.md`, not guessed here.';

        $out = base_path((string) $this->option('out'));
        @mkdir(dirname($out), 0775, true);
        file_put_contents($out, implode("\n", $md)."\n");
        $this->info('Wrote '.str_replace(base_path().'/', '', $out)." ({$seeded} of ".count($settings).' settings already seeded).');

        return self::SUCCESS;
    }
}
